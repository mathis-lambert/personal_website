/**
 * Export the content collections into `migrations/baseline/`, so both the data
 * and its shape are versioned in git.
 *
 *   MONGODB_URI=... MONGODB_DB=... node scripts/export-baseline.mjs
 *   npm run baseline:export          # reads .env
 *
 * When the database is only reachable from the server, there is a second way in:
 *
 *   node scripts/export-baseline.mjs --from some-dump.json
 *
 * which skips the connection and derives the schema from a dump produced by hand
 * (see migrations/README.md for the mongosh one-liner). It matters that this is
 * the same code path rather than a second script: a schema file generated by
 * slightly different logic is worse than none, because the next diff against it
 * reports changes that never happened.
 *
 * Writes two files:
 *
 *   baseline/data.json    every document, `_id` stripped. Slugs are the stable
 *                         keys, so letting Mongo mint fresh ObjectIds on import
 *                         avoids carrying EJSON `$oid` wrappers through git.
 *   baseline/schema.json  every field path that appears, its types, and how many
 *                         documents have it. This is the part worth reading in a
 *                         diff: it tells you when a field quietly changed type or
 *                         stopped being written.
 *
 * Telemetry collections are never exported. They are large, they hold hashed
 * IPs, user agents and whatever visitors typed into the chat, and none of that
 * belongs in a repository.
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

import {
  CONTENT_COLLECTIONS,
  EXCLUDED_COLLECTIONS,
  connect,
} from "../migrations/lib.mjs";

const OUT_DIR = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
  "migrations",
  "baseline",
);

/** Legacy names still worth capturing, so an old database exports faithfully. */
const ALSO_EXPORT = ["articles"];

const typeOf = (value) => {
  if (value === null) return "null";
  if (Array.isArray(value)) return "array";
  if (value instanceof Date) return "date";
  return typeof value;
};

/**
 * Walk documents and record every field path.
 *
 * Arrays are summarised as one entry per path with `[]` appended rather than one
 * per index, otherwise a gallery of eight images produces eight field paths and
 * the schema file becomes unreadable.
 */
const describe = (documents) => {
  const fields = new Map();

  const visit = (value, prefix) => {
    const kind = typeOf(value);
    const entry = fields.get(prefix) ?? { types: new Set(), count: 0 };
    entry.types.add(kind);
    entry.count += 1;
    fields.set(prefix, entry);

    if (kind === "object") {
      for (const [key, child] of Object.entries(value)) {
        visit(child, prefix ? `${prefix}.${key}` : key);
      }
    } else if (kind === "array" && value.length > 0) {
      for (const item of value) visit(item, `${prefix}[]`);
    }
  };

  for (const doc of documents) {
    for (const [key, value] of Object.entries(doc)) visit(value, key);
  }

  return {
    documents: documents.length,
    fields: Object.fromEntries(
      [...fields.entries()].sort(([a], [b]) => a.localeCompare(b)).map(
        ([field, { types, count }]) => [
          field,
          {
            types: [...types].sort(),
            in: count,
            required: count === documents.length,
          },
        ],
      ),
    ),
  };
};

/** Read the documents from a live database. */
const fromDatabase = async () => {
  const { client, db, dbName, host } = await connect();
  try {
    const present = new Set(
      (await db.listCollections({}, { nameOnly: true }).toArray()).map(
        (entry) => entry.name,
      ),
    );

    const wanted = [...CONTENT_COLLECTIONS, ...ALSO_EXPORT].filter(
      (name) => present.has(name) && !EXCLUDED_COLLECTIONS.includes(name),
    );

    const collections = {};
    for (const name of wanted) {
      const documents = await db
        .collection(name)
        .find({}, { projection: { _id: 0 } })
        .sort({ date: -1, _id: 1 })
        .toArray();
      if (documents.length > 0) collections[name] = documents;
    }

    return { collections, source: dbName, origin: `${dbName} at ${host}` };
  } finally {
    await client.close();
  }
};

/** Read the documents from a dump produced by hand on the server. */
const fromFile = async (file) => {
  const parsed = JSON.parse(await readFile(file, "utf8"));
  const collections = parsed.collections ?? parsed;

  const rejected = Object.keys(collections).filter((name) =>
    EXCLUDED_COLLECTIONS.includes(name),
  );
  if (rejected.length > 0) {
    throw new Error(
      `refusing to version telemetry collections: ${rejected.join(", ")}. ` +
        "Re-export without them.",
    );
  }

  for (const [name, documents] of Object.entries(collections)) {
    if (!Array.isArray(documents)) {
      throw new Error(`\`${name}\` is not an array of documents`);
    }
    if (documents.some((doc) => doc._id !== undefined)) {
      throw new Error(
        `\`${name}\` still has _id fields. Re-export with a { _id: 0 } projection.`,
      );
    }
  }

  return {
    collections,
    source: parsed.source ?? path.basename(file),
    origin: file,
  };
};

const fromIndex = process.argv.indexOf("--from");
const { collections, source, origin } =
  fromIndex === -1
    ? await fromDatabase()
    : await fromFile(process.argv[fromIndex + 1]);

const schema = {};
for (const [name, documents] of Object.entries(collections)) {
  schema[name] = describe(documents);
  console.log(
    `  ${name}: ${documents.length} document(s), ${Object.keys(schema[name].fields).length} field path(s)`,
  );
}

if (Object.keys(collections).length === 0) {
  console.log("Nothing to export: no content collections have documents.");
} else {
  await mkdir(OUT_DIR, { recursive: true });

  await writeFile(
    path.join(OUT_DIR, "data.json"),
    `${JSON.stringify({ source, collections }, null, 2)}\n`,
  );
  await writeFile(
    path.join(OUT_DIR, "schema.json"),
    `${JSON.stringify(schema, null, 2)}\n`,
  );

  console.log(`\nWrote migrations/baseline/{data,schema}.json from ${origin}`);
}
